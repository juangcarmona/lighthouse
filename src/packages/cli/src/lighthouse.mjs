#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = process.cwd();
const manifestPath = resolve(root, 'lighthouse.json');
const projection = 'LIGHTHOUSE.md';
const usage = 'Usage: lighthouse <init|verify>';

function render(manifest) {
  return `<!-- Generated by Lighthouse. Edit lighthouse.json and regenerate this file. -->\n\n# ${manifest.product} repository baseline\n\n- Baseline: \`${manifest.baseline}\`\n- Product: \`${manifest.product}\`\n- Profiles: ${manifest.profiles.length ? manifest.profiles.map((x) => `\`${x}\``).join(', ') : 'none'}\n- ProductShape: ${manifest.integrations.productShape ?? 'not adopted'}\n- ArcShape: ${manifest.integrations.arcShape ?? 'not adopted'}\n- Agentic SDLC: ${manifest.integrations.agenticSdlc ?? 'not adopted'}\n\n## How delivery works\n\nUse ProductShape for product intent and Product Changes, and use ArcShape for applicable architecture decisions; they can advance independently. Lighthouse carries the selected authority context through the delivery stages.\n\nA greenfield project initializes both authorities through their supported provider routes. An existing project can adopt them incrementally after its ownership and managed paths are assessed. The adoption contract includes a check of the external CodeGraph MCP service, its current git-root binding and the canonical repository and active worktrees; its index and credentials stay outside the checkout.\n\n1. \`triage\` classifies the work item, estimates complexity and blast radius, records urgency, impact, dependencies and risk, and sets configured workflow labels.\n2. \`refine\` defines the problem and stops at Ready.\n3. \`propose\` creates the solution and stops at Planned.\n4. \`implement\` applies the accepted plan and stops at Done.\n5. \`integrate\` updates the tracker, maintains the PR stack and closes the repository loop.\n6. \`review\` records learning after completion.\n\nThese are lifecycle capabilities. The baseline CLI currently provides \`init\` and \`verify\`; a configured OpenSpec, tracker or agent-host integration supplies the stage commands.\n\nChoose supervised work when a person steers each stage, plan-only work when only the proposal is needed, \`ff\` for a bounded unattended route, \`hotfix\` for a confirmed defect or \`decompose\` for a large item that needs ordered child issues and stacked PRs.\n\nThis file is managed. Put repository-specific policy in its own documentation and keep this projection generated from \`lighthouse.json\`.\n`;
}

function validate(m) {
  const problems = [];
  if (!m || typeof m !== 'object' || Array.isArray(m)) return ['manifest must be an object'];
  const allowed = ['$schema', 'schemaVersion', 'baseline', 'product', 'profiles', 'integrations', 'managed'];
  for (const key of Object.keys(m)) if (!allowed.includes(key)) problems.push(`unknown field ${key}`);
  for (const key of ['schemaVersion', 'baseline', 'product', 'profiles', 'integrations', 'managed']) if (!(key in m)) problems.push(`missing ${key}`);
  if (m.schemaVersion !== 1) problems.push('schemaVersion must be 1');
  if (m.baseline !== '0.1.0') problems.push('this verifier supports baseline 0.1.0');
  if ('$schema' in m && typeof m.$schema !== 'string') problems.push('$schema must be a string');
  if (typeof m.product !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9 ._-]{0,63}$/.test(m.product)) problems.push('product must be a readable name of 1–64 characters');
  const profiles = ['node-tooling', 'dotnet-backend', 'visual-theme'];
  if (!Array.isArray(m.profiles) || m.profiles.some((p) => !profiles.includes(p)) || new Set(m.profiles).size !== m.profiles.length) problems.push('profiles must be unique supported profile names');
  const integrations = m.integrations;
  const keys = ['productShape', 'arcShape', 'agenticSdlc'];
  const pin = /^(?:\d+\.\d+\.\d+|[a-f0-9]{40})$/;
  if (!integrations || typeof integrations !== 'object' || Array.isArray(integrations)
      || Object.keys(integrations).length !== keys.length
      || keys.some((k) => !(k in integrations) || (integrations[k] !== null && (typeof integrations[k] !== 'string' || !pin.test(integrations[k])))))
    problems.push('integrations must declare productShape, arcShape and agenticSdlc as exact versions, commit hashes or null');
  if (!Array.isArray(m.managed) || m.managed.length !== 1 || m.managed[0] !== projection) problems.push(`only ${projection} is managed by this version`);
  return problems;
}

const command = process.argv[2];
if (!['init', 'verify'].includes(command)) { console.error(usage); process.exit(2); }
let manifest;
try { manifest = JSON.parse(await readFile(manifestPath, 'utf8')); }
catch (error) { console.error(`Cannot read lighthouse.json: ${error.message}`); process.exit(1); }
const problems = validate(manifest);
if (problems.length) { console.error(problems.map((p) => `Invalid lighthouse.json: ${p}`).join('\n')); process.exit(1); }
const expected = render(manifest);
const target = resolve(root, projection);
if (command === 'init') {
  try { await readFile(target); console.error(`${projection} already exists; refusing to overwrite it. Review the manifest and manage the file explicitly.`); process.exit(1); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  await writeFile(target, expected, { flag: 'wx' });
  console.log(`Created ${projection} from lighthouse.json.`);
} else {
  try {
    const actual = await readFile(target, 'utf8');
    if (actual !== expected) { console.error(`${projection} has drifted. Regenerate it from lighthouse.json or restore the generated content.`); process.exit(1); }
  } catch (error) {
    if (error.code === 'ENOENT') { console.error(`${projection} is missing; run lighthouse init after reviewing the manifest.`); process.exit(1); }
    throw error;
  }
  console.log('Lighthouse manifest and managed projection are valid.');
}
