using System.Collections.Immutable;
using JuanGCarmona.Lighthouse.Analyzers;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using Xunit;

namespace JuanGCarmona.Lighthouse.Tests;

public class BackendContractTests
{
    private const string Contracts = """
        namespace JuanGCarmona.Lighthouse.Cqrs {
            public interface ICommandHandler<TCommand, TResponse> { }
            public interface IQueryHandler<TQuery, TResponse> { }
        }
        """;
    private static readonly ImmutableArray<MetadataReference> References =
        ((string)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES")!).Split(Path.PathSeparator)
            .Select(p => (MetadataReference)MetadataReference.CreateFromFile(p)).ToImmutableArray();

    [Theory]
    [InlineData("public sealed class Save : JuanGCarmona.Lighthouse.Cqrs.ICommandHandler<int, int> {}")]
    [InlineData("internal class Save : JuanGCarmona.Lighthouse.Cqrs.ICommandHandler<int, int> {}")]
    [InlineData("public sealed record Read : JuanGCarmona.Lighthouse.Cqrs.IQueryHandler<int, int>;")]
    public async Task HandlerContractReportsVisibilityOrInheritanceExposure(string declaration)
    {
        var diagnostics = await Analyze(Compile(Contracts + declaration));
        Assert.Single(diagnostics, d => d.Id == "LH1001" && d.Severity == DiagnosticSeverity.Error);
    }

    [Fact]
    public async Task InternalSealedHandlerPassesAndANameAloneDoesNotTriggerARule()
    {
        var source = Contracts + """
            internal sealed class Save : JuanGCarmona.Lighthouse.Cqrs.ICommandHandler<int, int> {}
            public class PresentationHandler {}
            """;
        Assert.Empty(await Analyze(Compile(source)));
    }

    [Fact]
    public async Task GeneratedHandlerIsIgnored()
    {
        Assert.Empty(await Analyze(Compile("// <auto-generated/>\n" + Contracts +
            "public class Generated : JuanGCarmona.Lighthouse.Cqrs.ICommandHandler<int, int> {}")));
    }

    [Fact]
    public async Task RuleIsOptInForModuleProjects()
    {
        var source = Contracts + "public class Save : JuanGCarmona.Lighthouse.Cqrs.ICommandHandler<int, int> {}";
        Assert.Empty(await Analyze(Compile(source), enabled: false));
    }

    [Theory]
    [InlineData("JuanGCarmona.Fixture.Modules.Other", true)]
    [InlineData("JuanGCarmona.Fixture.Modules.Other.Contracts", false)]
    [InlineData("SomeLibrary.Modules.Other", false)]
    public async Task ModuleRuleDistinguishesImplementationContractAndUnrelatedLibrary(string dependency, bool forbidden)
    {
        var assembly = Compile("public sealed class Export {}", dependency);
        using var stream = new MemoryStream();
        var emitted = assembly.Emit(stream);
        Assert.True(emitted.Success, string.Join("\n", emitted.Diagnostics));
        var reference = MetadataReference.CreateFromImage(stream.ToArray());
        var source = Compile("internal sealed class Local {}", "JuanGCarmona.Fixture.Modules.Main")
            .AddReferences(reference);
        var diagnostics = await Analyze(source);
        Assert.Equal(forbidden ? 1 : 0, diagnostics.Count(d => d.Id == "LH1002"));
    }

    private static CSharpCompilation Compile(string source, string name = "JuanGCarmona.Fixture.Modules.Main") =>
        CSharpCompilation.Create(name, [CSharpSyntaxTree.ParseText(source)], References,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

    private static async Task<ImmutableArray<Diagnostic>> Analyze(CSharpCompilation compilation, bool enabled = true)
    {
        Assert.Empty(compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error));
        var options = new AnalyzerOptions(ImmutableArray<AdditionalText>.Empty, new ModuleOptions(enabled));
        return await compilation.WithAnalyzers(
            ImmutableArray.Create<DiagnosticAnalyzer>(new BackendContractAnalyzer()), options)
            .GetAnalyzerDiagnosticsAsync();
    }

    private sealed class ModuleOptions(bool enabled) : AnalyzerConfigOptionsProvider
    {
        public override AnalyzerConfigOptions GlobalOptions { get; } = new Values(enabled);
        public override AnalyzerConfigOptions GetOptions(SyntaxTree tree) => GlobalOptions;
        public override AnalyzerConfigOptions GetOptions(AdditionalText textFile) => GlobalOptions;
    }

    private sealed class Values(bool enabled) : AnalyzerConfigOptions
    {
        public override bool TryGetValue(string key, out string value)
        {
            value = enabled ? "true" : "false";
            return key == "build_property.LighthouseModule";
        }
    }
}
